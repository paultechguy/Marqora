<#
.SYNOPSIS
    Applies the Marqora copyright and licence header to every hand-written C# file.

.DESCRIPTION
    Two lines at the top of each file: the copyright and an SPDX identifier. Apache-2.0
    does not require a per-file header, so the short machine-readable form is used rather
    than the thirteen-line boilerplate from the licence appendix. LICENSE at the repo root
    is the authority; these headers only travel with a file that leaves it.

    The script is idempotent. An existing header is rewritten rather than duplicated, so
    changing the year or the owner below and re-running is all a refresh takes.

    Generated code is skipped: obj/ and bin/, the XAML partials (*.g.cs, *.g.i.cs),
    designer files, and anything carrying an <auto-generated> marker.

.PARAMETER Check
    Report files that are missing or have an out-of-date header and exit non-zero.
    Nothing is written. This is the form to call from CI.

.PARAMETER Path
    Directories to scan, relative to the repo root. Defaults to src and tests.

.EXAMPLE
    pwsh ./build/Add-FileHeaders.ps1

.EXAMPLE
    pwsh ./build/Add-FileHeaders.ps1 -Check
#>
[CmdletBinding(SupportsShouldProcess)]
param(
    [switch]$Check,
    [string[]]$Path = @('src', 'tests')
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

# The one place the header is written. Keep in step with LICENSE and Directory.Build.props.
$owner   = 'Paul Carver'
$year    = '2026'
$licence = 'Apache-2.0'

$header = "// Copyright (c) $year $owner`r`n// SPDX-License-Identifier: $licence`r`n"

# Matches a header this script wrote, whatever year or owner it carried, plus the blank
# line under it. Anchored to the start so it only ever takes the file's own header.
$existing = '^//[ \t]*Copyright[^\r\n]*\r?\n//[ \t]*SPDX-License-Identifier:[^\r\n]*\r?\n(\r?\n)?'

$repoRoot = Split-Path -Parent $PSScriptRoot
$utf8NoBom = [System.Text.UTF8Encoding]::new($false)

$skipNames = @('*.g.cs', '*.g.i.cs', '*.Designer.cs', '*.AssemblyInfo.cs', '*.AssemblyAttributes.cs')

function Test-Generated {
    param([string]$Text)

    # Only the head of the file: the marker is a header convention, and the phrase can
    # legitimately appear further down in a comment about generated code.
    $head = $Text.Substring(0, [Math]::Min(600, $Text.Length))

    return $head -match '<auto-generated' -or $head -match '// *<autogenerated'
}

$files = foreach ($relative in $Path) {
    $root = Join-Path $repoRoot $relative
    if (-not (Test-Path $root)) {
        Write-Warning "skipping $relative (not found)"
        continue
    }

    Get-ChildItem -Path $root -Filter '*.cs' -Recurse -File |
        Where-Object { $_.FullName -notmatch '[\\/](obj|bin)[\\/]' } |
        Where-Object {
            $name = $_.Name
            -not ($skipNames | Where-Object { $name -like $_ })
        }
}

$changed = @()
$skipped = 0

foreach ($file in $files) {
    $text = [System.IO.File]::ReadAllText($file.FullName)

    if (Test-Generated $text) {
        $skipped++
        continue
    }

    $body = [regex]::Replace($text, $existing, '')
    $updated = $header + "`r`n" + $body

    if ($updated -ceq $text) {
        continue
    }

    $changed += $file

    if ($Check) {
        continue
    }

    if ($PSCmdlet.ShouldProcess($file.FullName, 'Add licence header')) {
        [System.IO.File]::WriteAllText($file.FullName, $updated, $utf8NoBom)
    }
}

$scanned = @($files).Count

if ($Check) {
    if ($changed.Count -gt 0) {
        Write-Host "Missing or stale licence header in $($changed.Count) of $scanned file(s):" -ForegroundColor Red
        foreach ($file in $changed) {
            Write-Host "  $([System.IO.Path]::GetRelativePath($repoRoot, $file.FullName))" -ForegroundColor DarkGray
        }

        Write-Host "Run: pwsh ./build/Add-FileHeaders.ps1" -ForegroundColor Yellow
        exit 1
    }

    Write-Host "Licence header present in all $scanned file(s)." -ForegroundColor Green
    exit 0
}

Write-Host "Headers written: $($changed.Count)" -ForegroundColor Green
Write-Host "Already current: $($scanned - $changed.Count)" -ForegroundColor DarkGray
if ($skipped -gt 0) {
    Write-Host "Generated, skipped: $skipped" -ForegroundColor DarkGray
}
