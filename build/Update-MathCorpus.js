/*
    Rebuilds the math corpus the Word exporter's tests run against.

        node build/Update-MathCorpus.js            # rewrite the fixture
        node build/Update-MathCorpus.js --check    # report only, non-zero exit if stale

    The exporter turns KaTeX's MathML into Word's OMML, so the only fixture worth testing
    against is MathML a browser actually produced. Hand-written MathML approximates the shape
    and misses the wrappers - which is how every matrix, aligned system and set of cases came
    to be silently unconvertible for the life of the feature while the tests stayed green.

    So this renders every display equation in docs/UltimateMarkdownContent.md with the same
    KaTeX the app ships - webshell/vendor/katex - and writes the two files the test reads:

      MathCorpus.md            the equations as markdown, one $$ block each
      MathCorpus.preview.html  each equation's <math>, stamped with the line its block opens
                               on, which is what PreviewHarvest keys everything to

    Run it after changing that document's math, or after taking a new KaTeX. The test asserts
    every equation converts, so a KaTeX that begins emitting something the converter does not
    know fails the build rather than quietly turning into TeX source in everybody's documents.
*/

const fs = require("fs");
const path = require("path");

const root = path.resolve(__dirname, "..");
const katex = require(path.join(root, "webshell/vendor/katex/katex.min.js"));

const source = path.join(root, "docs/UltimateMarkdownContent.md");
const folder = path.join(root, "tests/PaulTechGuy.MQ.Docx.Tests/Fixtures");
const check = process.argv.includes("--check");

/**
 * The header both files carry. An HTML comment in each: markdown passes one through, and the
 * harvest only ever looks for <math> and data-src-line, so neither file minds.
 */
function banner(what) {
  return [
    "<!--",
    "  Generated by build/Update-MathCorpus.js from docs/UltimateMarkdownContent.md.",
    `  ${what}`,
    `  KaTeX ${katex.version}. Do not edit by hand - run the script.`,
    "-->",
    "",
  ];
}

/** Every fenced display-math block in the document, in order. */
function displayBlocks(text) {
  const blocks = [];
  let open = null;

  text.split(/\r?\n/).forEach((line) => {
    if (line.trim() === "$$") {
      if (open === null) { open = []; } else { blocks.push(open); open = null; }
    } else if (open !== null) {
      open.push(line);
    }
  });

  return blocks;
}

const blocks = displayBlocks(fs.readFileSync(source, "utf8"));
const markdown = banner("The equations, one $$ block each.");
const html = banner("Each equation's MathML, stamped with its block's line.");

for (const block of blocks) {
  const tex = block.join("\n");
  const rendered = katex.renderToString(tex, { displayMode: true, throwOnError: false });
  const math = rendered.match(/<math[\s\S]*?<\/math>/);

  if (!math) {
    console.error(`KaTeX could not render this block, so it would have no MathML:\n${tex}`);
    process.exit(1);
  }

  // The line the "$$" lands on, counted from zero, which is what Markdig reports for the
  // block and therefore what the preview stamp has to say.
  const line = markdown.length;

  markdown.push("$$", ...block, "$$", "");
  html.push(`<div class="math" data-src-line="${line}">${math[0]}</div>`);
}

const files = {
  "MathCorpus.md": markdown.join("\n"),
  "MathCorpus.preview.html": html.join("\n"),
};

let stale = false;

fs.mkdirSync(folder, { recursive: true });

for (const [name, content] of Object.entries(files)) {
  const target = path.join(folder, name);
  const current = fs.existsSync(target) ? fs.readFileSync(target, "utf8") : null;

  if (current === content) {
    continue;
  }

  stale = true;

  if (check) {
    console.error(`${name} is out of date.`);
    continue;
  }

  fs.writeFileSync(target, content, "utf8");
  console.log(`Wrote ${name}.`);
}

if (check && stale) {
  console.error("Run: node build/Update-MathCorpus.js");
  process.exit(1);
}

console.log(`${blocks.length} display equations, KaTeX ${katex.version}.`);
